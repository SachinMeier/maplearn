import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { maps } from '../maps.js';

export async function writeOfflineManifest(root) {
  const scripts = (await readdir(root)).filter(name => name.endsWith('.js') &&
    !['sw.js', 'offline-manifest.js'].includes(name) && !name.endsWith('.config.js')).sort();
  const shell = ['index.html', 'styles.css', ...scripts, 'assets/icons.svg', 'assets/globe.svg',
    'favicon.ico', 'site.webmanifest',
    ...[16, 32, 48, 180, 192, 512].map(size => `assets/favicons/icon-${size}.png`),
    ...maps.map(map => `assets/maps/${map.id}.thumbnail.svg`)];
  const hash = async files => {
    const digest = createHash('sha256');
    for (const path of files) digest.update(path).update(await readFile(new URL(path, root)));
    return digest.digest('hex').slice(0, 20);
  };
  const catalog = [];
  for (const map of maps) {
    const files = [map.svg, map.countries, map.svg.replace('.svg', '.manifest.json')]
      .map(path => path.replace(/^\.\//, ''));
    let bytes = 0;
    const fileHashes = {};
    for (const path of files) {
      const data = await readFile(new URL(path, root));
      bytes += data.length;
      fileHashes[path] = createHash('sha256').update(data).digest('hex');
    }
    catalog.push({ id: map.id, files, fileHashes, bytes, version: await hash(files) });
  }
  await writeFile(new URL('offline-catalog.json', root), JSON.stringify({ maps: catalog }) + '\n');
  // A map-only release must also get an isolated catalog/interface cache.
  const version = createHash('sha256').update(await hash([...shell, 'sw.js']))
    .update(JSON.stringify(catalog)).digest('hex').slice(0, 20);
  await writeFile(new URL('offline-manifest.js', root),
    `// Generated by scripts/offline-manifest.mjs.\nself.OFFLINE_MANIFEST = ${JSON.stringify({ version, shell, maps: catalog })};\n`);
}

if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file:').href) {
  await writeOfflineManifest(new URL('../', import.meta.url));
}
